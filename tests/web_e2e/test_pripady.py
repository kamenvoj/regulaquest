    p.evaluate(f"openUnit('{unit2}')"); time.sleep(1)
    p.click('#rqRelBox summary'); time.sleep(0.2); p.click('#rqCaseAdd'); time.sleep(0.2); p.locator('[data-case-add]').first.click(); time.sleep(1)
