    print('případ: kroky', r.locator('.cs-steps > li').count(), '| tabulka', r.locator('.cs-box.concl table').count(), '| odrážky', r.locator('.cs-box.assign li').count(), '| souvisí', r.locator('.fr-list.units li').count())
