    p.click('[data-ssave]'); time.sleep(0.9)
    p.click('#csAddStep'); time.sleep(0.2); p.fill('[data-st]', 'Určení třídy'); p.fill('[data-sb]', 'Podle pravidla 11.'); p.click('[data-ssave]'); time.sleep(0.9)
